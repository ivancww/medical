const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('app.js','utf8');
const start=source.indexOf('function p7WiseDifferenceHtml(');
const end=source.indexOf('function wiseStatusBlock(',start);
assert.ok(start>=0&&end>start,'P7 comparison highlighter exists');
const sandbox={esc:(s)=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;'),comparisonHasDisplayData:v=>Boolean(v&&(v.main_value||v.sub_value))};
vm.createContext(sandbox);
vm.runInContext(source.slice(start,end),sandbox);
const item={values:{WISE:{WISE_SEMI_PRIVATE:{main_value:'全數賠償',sub_value:'手術前30天'},WISE_GENERAL_ROOM:{main_value:'上限 $640',sub_value:'手術前30天 · 限1次'}}}};
const semi=sandbox.p7WiseDifferenceHtml(item,['全數賠償','手術前30天'],true);
const general=sandbox.p7WiseDifferenceHtml(item,['上限 $640','手術前30天 · 限1次'],false);
assert.match(semi.main,/color:#2563EB/);
assert.match(general.main,/color:#DC2626/);
assert.doesNotMatch(semi.sub,/color:/,'identical pre-op period remains neutral');
assert.match(general.sub,/手術前30天/);
assert.match(general.sub,/color:#DC2626[^>]*>限1次/);
assert.doesNotMatch(general.sub,/<span[^>]*>手術前30天/,'common period not highlighted');
const equal={values:{WISE:{WISE_SEMI_PRIVATE:{main_value:'全數賠償',sub_value:'相同'},WISE_GENERAL_ROOM:{main_value:'全數賠償',sub_value:'相同'}}}};
assert.doesNotMatch(JSON.stringify(sandbox.p7WiseDifferenceHtml(equal,['全數賠償','相同'],true)),/color:/);
assert.equal(sandbox.p7WiseDifferenceHtml({values:{WISE:{WISE_SEMI_PRIVATE:item.values.WISE.WISE_SEMI_PRIVATE}}},['全數賠償','手術前30天'],true),null);
const malicious={values:{WISE:{WISE_SEMI_PRIVATE:{main_value:'<script>',sub_value:''},WISE_GENERAL_ROOM:{main_value:'不同',sub_value:''}}}};
assert.match(sandbox.p7WiseDifferenceHtml(malicious,['<script>',''],true).main,/&lt;script&gt;/);
console.log('P7 Wise difference-only color regression passed');
